async def resolve_turn(
    session: dict,
    party: list,
    actions: list,
    stream_callback=None,
    is_retry: bool = False,
    ctx: Optional[TurnExecutionContext] = None,
) -> TurnOutcome:
    try:
        return await _resolve_turn_inner(
            session,
            party,
            actions,
            stream_callback=stream_callback,
            is_retry=is_retry,
            ctx=ctx,
        )
    finally:
        if isinstance(session, dict):
            session.pop("_ctx", None)


async def _resolve_turn_inner(
    session: dict,
    party: list,
    actions: list,
    stream_callback=None,
    is_retry: bool = False,
    ctx: Optional[TurnExecutionContext] = None,
) -> TurnOutcome:
    pre_state = await run_pre_turn_phase(
        session,
        party,
        actions,
        is_retry=is_retry,
        ctx=ctx,
    )
    ctx = pre_state.ctx
    llm_state = await assemble_and_call_turn_llm(
        session,
        party,
        actions,
        pre_state,
        stream_callback=stream_callback,
    )
    return await run_post_turn_phase(
        session,
        party,
        actions,
        pre_state,
        llm_state,
        stream_callback=stream_callback,
        is_retry=is_retry,
    )


async def evaluate_action(
    session_id: int,
    user_action: str,
    party: list,
    current_location: str = "",
    current_npcs: list | None = None,
    nearby_enemies: list | None = None,
    history_text: str = "",
) -> dict:
    """Evaluate a synthetic or system-initiated action against a session via resolve_turn."""
    from skill_check import CheckResult
    session = (await adb(db.get_session, session_id)) or {
        "id": session_id,
        "current_location": current_location,
        "current_npcs": current_npcs or [],
        "nearby_enemies": nearby_enemies or [],
        "history": [history_text] if history_text else [],
    }
    session.setdefault("history", [history_text] if history_text else [])
    actor_char = (
        party[0][0]
        if party and isinstance(party[0], (list, tuple)) and party[0]
        else (party[0] if party and isinstance(party[0], dict) else {"name": "Adventurer", "user_id": 0, "max_hp": 100})
    )
    actions = [{
        "char": actor_char,
        "character": actor_char,
        "label": user_action,
        "action": user_action,
        "mp_spent": 0,
        "check": CheckResult(
            chance=100, roll=100.0, tier="success",
            tier_label="Success", succeeded=True, requirement=0
        ),
        "roll": None,
        "stat": "CHA",
        "stat_mod": 0,
        "total": None,
    }]
    outcome = await resolve_turn(session, party, actions)
    if hasattr(outcome, "to_dict"):
        d = outcome.to_dict()
    elif isinstance(outcome, dict):
        d = dict(outcome)
    else:
        d = {}
    d.setdefault("outcome_narrative", d.get("next_narrative") or d.get("narrative", ""))
    d.setdefault("npcs_present", d.get("current_npcs", current_npcs or []))
    d.setdefault("location", d.get("new_location") or current_location)
    return d








